/**
 * Build "Javelin Coder 7B" as a local Ollama model.
 * =================================================
 *
 *   npm run model:local            # create/refresh the local Javelin model
 *   npm run model:local --show  # print the generated Modelfile, create nothing
 *
 * Why this exists
 * ---------------
 * A full 80B fine-tune is out of reach on consumer hardware, but "my own model
 * running on my own computer" is not: Ollama can build a *derived* model from any
 * local base, baking in a system prompt, parameters and a template. That produces a
 * real model — `javelin-coder` — that runs entirely on this machine, with Javelin's
 * identity and standards as its system prompt.
 *
 * Honesty note: this is a *derived* model, not a trained one. It adopts Javelin's
 * character via the system prompt; it does not have Javelin's behaviour in its
 * weights. `derive` is recorded as the method so nothing here can be mistaken for a
 * fine-tune. What it gives you is a local, keyless, offline Javelin-branded coder
 *today*, wired to the exact identity the runtime serves.
 */

import { execFileSync } from 'node:child_process'
import { writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

import { MODEL_IDENTITY, MODEL_PRINCIPLES } from '../src/core/identity.js'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')

const MODEL_NAME = 'javelin-coder'

/** Candidate local bases, best first. Must support tools. */
const BASE_CANDIDATES = [
  'qwen2.5-coder:7b',
  'qwen2.5-coder:14b',
  'qwen2.5-coder:3b',
  'llama3.1:8b',
  'codellama:13b',
  'qwen3.5:2b',
]

function findOllama() {
  const candidates = [
    join(process.env.LOCALAPPDATA ?? '', 'Programs', 'Ollama', 'ollama.exe'),
    'ollama',
  ]
  for (const c of candidates) {
    if (c === 'ollama') {
      return c // let the shell resolve it
    }
    if (existsSync(c)) {
      return c
    }
  }
  return 'ollama'
}

function ollamaList(exe) {
  try {
    const out = execFileSync(exe, ['list'], { encoding: 'utf8', timeout: 20_000 })
    return out
      .split('\n')
      .slice(1)
      .map((l) => l.trim().split(/\s{2,}/)[0])
      .filter(Boolean)
  } catch {
    return []
  }
}

/** The system prompt: the same identity the runtime serves, plus a local note. */
export function buildSystemPrompt() {
  const standards = MODEL_PRINCIPLES.map((p, i) => `${i + 1}. ${p.text}`).join('\n')
  return [
    MODEL_IDENTITY,
    '',
    'WORKING STANDARDS',
    standards,
    '',
    'You are running locally on the user\'s own machine. You have access to file and',
    'command tools through the host application; call them to act rather than describing',
    'what you would do.',
    '',
    'TOOL CALL FORMAT (strict):',
    'When you call a tool, emit ONLY a <tool_call> block containing a single JSON object.',
    'Do NOT wrap it in backticks, do NOT write ```json, and do NOT add any text around it.',
    'Example:',
    '<tool_call>',
    '{"name": "list_files", "arguments": {"path": "."}}',
    '</tool_call>',
  ].join('\n')
}

export function buildModelfile(base) {
  return [
    `# Javelin Coder — local derived model.`,
    `# Generated by training/build-local-model.mjs — edit that file, not this one.`,
    `#`,
    `# This is a DERIVED model: it adopts Javelin's identity via the system prompt.`,
    `# It is NOT a fine-tune — no weights were trained. See docs/TRAINING.md.`,
    '',
    `FROM ${base}`,
    '',
    '# Coding-tuned defaults: low temperature for correctness, generous context.',
    'PARAMETER temperature 0.2',
    'PARAMETER top_p 0.9',
    'PARAMETER num_ctx 8192',
    '',
    'SYSTEM """',
    buildSystemPrompt(),
    '"""',
    '',
  ].join('\n')
}

function main() {
  const args = process.argv.slice(2)
  const showOnly = args.includes('--show') || args.includes('--dry-run')
  const baseArgIndex = args.indexOf('--base')
  const baseOverride = baseArgIndex !== -1 ? args[baseArgIndex + 1] : null

  const exe = findOllama()

  console.log('\n=== Build local Javelin model ===\n')

  if (baseOverride) {
    console.log(`  base      : ${baseOverride} (explicit)`)
  } else if (!showOnly) {
    const installed = ollamaList(exe)
    if (installed.length === 0) {
      console.error('  ERROR: no local models found, or Ollama is not reachable.')
      console.error('  Start Ollama, pull a coder model, then retry:')
      console.error('    ollama pull qwen2.5-coder:7b\n')
      process.exit(1)
    }
    console.log(`  local models: ${installed.join(', ')}`)
  }

  const base = baseOverride ?? BASE_CANDIDATES.find((b) => {
    try {
      return ollamaList(exe).includes(b)
    } catch {
      return false
    }
  }) ?? BASE_CANDIDATES[0]

  const modelfile = buildModelfile(base)

  console.log(`  model name: ${MODEL_NAME}`)
  console.log(`  base      : ${base}`)
  console.log(`  method    : DERIVED (system prompt) — not a fine-tune`)

  const outPath = join(root, 'training', 'Modelfile.local')
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, modelfile, 'utf8')
  console.log(`  modelfile : ${outPath}`)

  if (showOnly) {
    console.log('\n--- Modelfile ---\n')
    console.log(modelfile)
    return
  }

  console.log(`\n  Creating "${MODEL_NAME}" in Ollama …`)
  try {
    execFileSync(exe, ['create', MODEL_NAME, '-f', outPath], { stdio: 'inherit', timeout: 300_000 })
  } catch (err) {
    console.error(`\n  ERROR: ollama create failed — ${err.message}`)
    console.error('  Is Ollama running?  Start it, then retry.\n')
    process.exit(1)
  }

  console.log('\n  Done. Your model runs entirely on this machine.\n')
  console.log('  Use it in the app:')
  console.log(`    - Provider: Local (keyless)`)
  console.log(`    - Model   : ${MODEL_NAME}`)
  console.log('  Or from the terminal:')
  console.log(`    ollama run ${MODEL_NAME}`)
  console.log('\n  Reminder: this is a derived model, not a trained one. It has Javelin\'s')
  console.log('  identity, not Javelin\'s weights. See docs/TRAINING.md for the real path.\n')
}

main()
