/**
 * Fine-tune configuration generator.
 * ==================================
 *
 * Emits configuration for a LoRA / QLoRA fine-tune, plus the training script that
 * consumes it. Two deliberate choices:
 *
 *  1. **Configs are generated, not hand-written.** A hand-written config drifts
 *     from the dataset it was built for. Generating means hyperparameters and the
 *     training script are always consistent with the actual JDF data.
 *
 *  2. **We do not vendor a trainer.** Implementing a correct PEFT training loop from
 *     scratch would be worse than using the ecosystem's. Instead we emit a script
 *     built on `transformers` + `peft` + `trl` — the tools that are actually used
 *     for this — and state the dependency explicitly rather than pretending
 *     training is a self-contained thing.
 *
 * WHY LoRA FIRST: full fine-tuning of a 7B model needs ~8×A100 and weeks of
 * iteration. LoRA adapts a small number of parameters, runs on a single consumer
 * GPU, and can be merged back into the base weights afterwards. It is the correct
 * starting point by a wide margin.
 */

/**
 * Estimate the adapter size to choose sensible defaults.
 * Bigger dataset → more capacity before overfitting becomes the limit.
 */
export function recommendHyperparameters({ trainCount, modelSize = '7b' }) {
    const notes = []

    // LoRA rank controls adapter capacity. Too low underfits the style; too high
    // overfits a small dataset. These are deliberately conservative for small data.
    let rank = 16
    if (trainCount < 200) {
        rank = 8
        notes.push('Small dataset (<200): rank lowered to 8 to reduce overfitting.')
    } else if (trainCount > 5000) {
        rank = 32
        notes.push('Large dataset (>5000): rank raised to 32 to capture more behaviour.')
    }

    // Learning rate: LoRA tolerates higher LR than full fine-tuning.
    let learningRate = 1e-4
    if (trainCount < 500) {
        learningRate = 5e-5
        notes.push('Small dataset: learning rate halved to avoid memorising examples.')
    }

    // Enough epochs to learn style, few enough not to memorise.
    let epochs = 3
    if (trainCount < 300) {
        epochs = 5
        notes.push('Small dataset: more epochs so the policy is actually seen.')
    } else if (trainCount > 20000) {
        epochs = 1
        notes.push('Large dataset: a single epoch is sufficient.')
    }

    notes.push(
      'LoRA adapts attention projections only. QLoRA (4-bit base) fits a 7B model on ~6GB VRAM.',
    )
    notes.push(
      'Loss is computed on assistant tokens only — without this the model learns to ' +
        'generate tool RESULTS instead of tool CALLS, which is the classic agent fine-tune failure.',
    )

    return {
        rank,
        alpha: rank * 2, // alpha = 2×rank is the common, stable convention
        dropout: 0.05,
        learningRate,
        epochs,
        batchSize: 1,
        gradientAccumulation: 16,
        maxSeqLength: 4096,
        warmupRatio: 0.03,
        scheduler: 'cosine',
        targetModules: ['q_proj', 'k_proj', 'v_proj', 'o_proj'],
        notes,
    }
}

/**
 * Build a complete config object for one fine-tune run.
 */
export function buildFinetuneConfig({
  baseModel = 'Qwen/Qwen2.5-Coder-7B-Instruct',
  trainPath,
  validationPath,
  outputDir = 'training/runs/javelin-lora',
  trainCount = 0,
  validationCount = 0,
  quantization = '4bit',
  method = 'qlora',
  hardware = null,
  seed = 1337,
}) {
    const hyper = recommendHyperparameters({ trainCount })

    const useQuantization = method === 'qlora'

    return {
      _comment: [
        'Generated by training/finetune/config.mjs — edit that generator, not this file.',
        'This adapts a base model to Javelin\'s tool-calling and verify/repair policy.',
        'It does NOT create a new model from scratch; see docs/TRAINING.md.',
      ],
      baseModel,
      method,
      hardware,
      dataset: { trainPath, validationPath, trainCount, validationCount },
      output: { dir: outputDir, adapterName: 'javelin-lora', mergedDir: `${outputDir}/merged` },
      quantization: {
        // QLoRA loads the base in 4-bit. Plain LoRA keeps the base in bf16/fp16.
        // bitsandbytes (and therefore QLoRA) is Linux-only, so on Windows/AMD this
        // is false and the trainer takes the LoRA path.
        loadIn4Bit: useQuantization,
        bnbComputeDtype: 'bfloat16',
        quantType: 'nf4',
        doubleQuant: true,
      },
        lora: {
            r: hyper.rank,
            loraAlpha: hyper.alpha,
            loraDropout: hyper.dropout,
            targetModules: hyper.targetModules,
            bias: 'none',
            taskType: 'CAUSAL_LM',
        },
        training: {
            epochs: hyper.epochs,
            learningRate: hyper.learningRate,
            perDeviceBatchSize: hyper.batchSize,
            gradientAccumulationSteps: hyper.gradientAccumulation,
            maxSeqLength: hyper.maxSeqLength,
            warmupRatio: hyper.warmupRatio,
            lrScheduler: hyper.scheduler,
            bf16: true,
            gradientCheckpointing: true,
              loggingSteps: 10,
              saveSteps: 200,
              evalSteps: 100,
              saveTotalLimit: 3,
              seed,
              // On CPU, bf16 and gradient checkpointing behave differently; the trainer
              // branches on this rather than silently producing a broken run.
              device: hardware?.vramGb ? 'auto' : 'cpu',
              // Critical for our data: only compute loss on the assistant's target tokens,
              // not on the system prompt or tool output. Otherwise the model learns to
              // generate tool *results* rather than tool *calls*.
              trainOnAssistantResponsesOnly: true,
            },
        notes: hyper.notes,
    }
}

/**
 * Emit the training script. This is a real, runnable script — it is only emitted
 * rather than committed as a module because it needs a Python environment with
 * GPU support that this repository deliberately does not depend on.
 */
export function buildTrainingScript(config) {
    return `#!/usr/bin/env python3
"""
Javelin fine-tune — LoRA/QLoRA adapter training.

GENERATED FILE. Edit training/finetune/config.mjs and regenerate instead.

Requirements (a GPU is required; CPU training is impractically slow):
    pip install torch transformers peft trl datasets bitsandbytes accelerate

Then:
    python training/finetune/train.py
"""

import json
import os
import sys
import time
CONFIG_PATH = os.path.join(os.path.dirname(__file__), "config.json")


def load_config():
    with open(CONFIG_PATH, "r", encoding="utf-8") as fh:
        return json.load(fh)


def detect_device(torch):
    ""
    Report which accelerator is actually usable, without assuming CUDA.

    AMD users are the case this exists for: an RX 6000-series card on Windows has
    no working ROCm path, so PyTorch reports CPU. Rather than crashing, say so and
    continue on CPU where that is viable.
    ""
    if torch.cuda.is_available():
        total = torch.cuda.get_device_properties(0).total_memory / 1e9
        return "cuda", f"{torch.cuda.get_device_name(0)} ({total:.1f GB)"

    # ROCm builds of PyTorch report through torch.cuda but set torch.version.hip.
    hip_version = getattr(torch.version, "hip", None)
    if hip_version:
        return "rocm", f"AMD ROCm {hip_version} (reported via cuda)"

    if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
        return "mps", "Apple MPS"

    return "cpu", "CPU only"


def preflight(cfg):
    """Fail loudly and early rather than after an hour of setup."""
    try:
        import torch  # noqa: F401
    except ImportError:
        sys.exit(
            "ERROR: torch is not installed.\\n\\n"
            "  NVIDIA / CPU:  pip install torch transformers peft trl datasets accelerate\\n"
            "  AMD Linux:     install the ROCm PyTorch wheel, then the same packages plus bitsandbytes\\n"
            "  AMD Windows:   run  npm run train:prepare  for guidance\\n"
        )

    import torch
    for path_key in ("trainPath", "validationPath"):
        path = cfg["dataset"][path_key]
        if not os.path.exists(path):
            sys.exit(f"ERROR: dataset file not found: {path}\\n"
                     f"  Build it first:  npm run train:dataset")

    device, detail = detect_device(torch)
    method = cfg.get("method", "qlora")

    print(f"Device: {device} - {detail}")
    print(f"Method: {method}")
    print(f"Base model: {cfg['baseModel']}")
    print(f"Train records: {cfg['dataset']['trainCount']}")
    print(f"Validation records: {cfg['dataset']['validationCount']}")

    if device == "cpu":
        # Not an error: CPU LoRA on a small model genuinely works. But say plainly
        # what to expect, so nobody is surprised by the runtime.
        print()
        print("WARNING: no GPU accelerator is available; training will run on CPU.")
        print("  Viable for small models (<= ~1.5B) on a modest dataset, but slow.")
        print("  If this is an AMD card on Windows: AMD's ROCm preview covers Radeon")
        print("  7000/9000 only. A 6000-series card needs ROCm on Linux (WSL2).")
        print("  Continuing in 5s - press Ctrl+C to abort.")
        time.sleep(5)

    if method == "qlora" and device == "cpu":
        sys.exit(
            "ERROR: QLoRA needs bitsandbytes, which requires a CUDA/ROCm GPU.\\n"
            "  Regenerate with LoRA instead:\\n"
            "    npm run train:prepare --dataset <dir> --method lora"
        )

    return device


def load_datasets(cfg):
    """
    Load JDF records and convert them to chat-template text.

    Only assistant turns are supervised: the system prompt and tool results are
    context, not targets. Learning to *generate tool results* is a real failure
    mode for agent fine-tunes, and this is how it is avoided.
    """
    from datasets import load_dataset

    raw = load_dataset(
        "json",
        data_files={
            "train": cfg["dataset"]["trainPath"],
            "validation": cfg["dataset"]["validationPath"],
        },
    )

    def format_record(record):
        messages = record.get("messages") or []
        tools = record.get("tools") or []

        lines = []
        if tools:
            # Give the model the tool schemas it will be called with at inference.
            lines.append("AVAILABLE TOOLS:")
            for tool in tools:
                fn = tool.get("function", {})
                lines.append(f"  - {fn.get('name')}: {fn.get('description', '')}")
            lines.append("")

        for message in messages:
            role = message.get("role")
            content = message.get("content") or ""
            if role == "system":
                lines.append(f"<|system|>\\n{content}")
            elif role == "user":
                lines.append(f"<|user|>\\n{content}")
            elif role == "assistant":
                if message.get("tool_calls"):
                    calls = message["tool_calls"]
                    rendered = "\\n".join(
                        f"  {c['function']['name']}({c['function']['arguments']})" for c in calls
                    )
                    lines.append(f"<|assistant|>\\n<tool_call>\\n{rendered}\\n</tool_call>")
                else:
                    lines.append(f"<|assistant|>\\n{content}")
            elif role == "tool":
                lines.append(f"<|tool_result|>\\n{content}")

        return {"text": "\\n".join(lines)}

    return raw.map(format_record)


def main():
    cfg = load_config()
    device = preflight(cfg)

    import torch
    from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training
    from transformers import AutoModelForCausalLM, AutoTokenizer, TrainingArguments
    from trl import SFTTrainer
    quant = cfg["quantization"]
    bnb_config = None
    if quant["loadIn4Bit"]:
        try:
            from transformers import BitsAndBytesConfig
        except ImportError:
            sys.exit("ERROR: bitsandbytes is required for QLoRA. Re-run with --method lora.")
        bnb_config = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_quant_type=quant["quantType"],
            bnb_4bit_compute_dtype=torch.bfloat16,
            bnb_4bit_use_double_quant=quant["doubleQuant"],
        )

    tokenizer = AutoTokenizer.from_pretrained(cfg["baseModel"], trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    # device_map="auto" requires accelerate and assumes a GPU; on CPU it should be
    # left unset so the model is placed normally.
    load_kwargs = {"trust_remote_code": True}
    if bnb_config is not None:
        load_kwargs["quantization_config"] = bnb_config
        load_kwargs["device_map"] = "auto"
    elif device != "cpu":
        load_kwargs["torch_dtype"] = torch.bfloat16
        load_kwargs["device_map"] = "auto"

    model = AutoModelForCausalLM.from_pretrained(cfg["baseModel"], **load_kwargs)
    if quant["loadIn4Bit"]:
        model = prepare_model_for_kbit_training(model)

    lora = cfg["lora"]
    peft_config = LoraConfig(
        r=lora["r"],
        lora_alpha=lora["loraAlpha"],
        lora_dropout=lora["loraDropout"],
        target_modules=lora["targetModules"],
        bias=lora["bias"],
        task_type=lora["taskType"],
    )
    model = get_peft_model(model, peft_config)
    model.print_trainable_parameters()

    dataset = load_datasets(cfg)
    train_cfg = cfg["training"]

    # bf16 needs a GPU that supports it; CPU and older cards fall back to fp32.
    use_bf16 = bool(train_cfg["bf16"]) and device != "cpu"

    args = TrainingArguments(
        output_dir=cfg["output"]["dir"],
        num_train_epochs=train_cfg["epochs"],
        per_device_train_batch_size=train_cfg["perDeviceBatchSize"],
        gradient_accumulation_steps=train_cfg["gradientAccumulationSteps"],
        learning_rate=train_cfg["learningRate"],
        lr_scheduler_type=train_cfg["lrScheduler"],
        warmup_ratio=train_cfg["warmupRatio"],
        bf16=use_bf16,
        fp16=False,
        use_cpu=(device == "cpu"),
        gradient_checkpointing=bool(train_cfg["gradientCheckpointing"]) and device != "cpu",
        logging_steps=train_cfg["loggingSteps"],
        save_steps=train_cfg["saveSteps"],
        eval_steps=train_cfg["evalSteps"],
        save_total_limit=train_cfg["saveTotalLimit"],
        eval_strategy="steps",
        seed=train_cfg["seed"],
        report_to=[],
    )

    trainer = SFTTrainer(
        model=model,
        args=args,
        train_dataset=dataset["train"],
        eval_dataset=dataset["validation"],
        processing_class=tokenizer,
        peft_config=peft_config,
    )

    trainer.train()
    trainer.save_model(cfg["output"]["dir"])
    tokenizer.save_pretrained(cfg["output"]["dir"])
    print(f"\\nAdapter saved to {cfg['output']['dir']}")
    print("Merge into base weights with: python training/finetune/merge.py")


if __name__ == "__main__":
    main()
`
}

/** Emit the merge script — turns an adapter into standalone weights. */
export function buildMergeScript() {
    return `#!/usr/bin/env python3
"""
Merge a Javelin LoRA adapter into its base model.

Produces standalone weights, which is what you serve as a Javelin engine.

    python training/finetune/merge.py
"""

import json
import os
import sys

CONFIG_PATH = os.path.join(os.path.dirname(__file__), "config.json")


def main():
    with open(CONFIG_PATH, "r", encoding="utf-8") as fh:
        cfg = json.load(fh)

    try:
        import torch
        from peft import PeftModel
        from transformers import AutoModelForCausalLM, AutoTokenizer
    except ImportError:
        sys.exit("ERROR: install torch, transformers and peft first.")

    adapter_dir = cfg["output"]["dir"]
    merged_dir = cfg["output"]["mergedDir"]

    if not os.path.exists(adapter_dir):
        sys.exit(f"ERROR: no adapter at {adapter_dir}. Train one first.")

    print(f"Loading base model {cfg['baseModel']} …")
    base = AutoModelForCausalLM.from_pretrained(
        cfg["baseModel"], torch_dtype=torch.bfloat16, device_map="auto", trust_remote_code=True
    )
    tokenizer = AutoTokenizer.from_pretrained(cfg["baseModel"], trust_remote_code=True)

    print(f"Attaching adapter from {adapter_dir} …")
    model = PeftModel.from_pretrained(base, adapter_dir)

    print("Merging …")
    model = model.merge_and_unload()
    model.save_pretrained(merged_dir, safe_serialization=True)
    tokenizer.save_pretrained(merged_dir)

    print(f"\\nMerged model written to {merged_dir}")
    print("Serve it with Ollama (see docs/TRAINING.md) or load it as a Javelin engine.")


if __name__ == "__main__":
    main()
`
}
