/**
 * Javelin Dataset Format (JDF) — schema, version, and validator.
 * =============================================================
 *
 * This is the contract between Javelin's runtime and any training job. Recording,
 * export, validation and fine-tuning all speak JDF, so the format is defined once
 * and never re-invented per script.
 *
 * DESIGN DECISIONS, and why:
 *
 * 1. **Two record kinds, not one.** `sft` records are training examples. `trajectory`
 *    records are the raw, multi-step episodes Javelin's runtime produced. Keeping
 *    both means we can re-derive better SFT data later without re-running Javelin,
 *    and we keep the audit trail that proves where a training example came from.
 *
 * 2. **Tool calls are first-class, not text.** Javelin's whole value is that it
 *    drives tools inside a verify/repair loop. A format that only stored strings
 *    could not teach that. So `messages[]` supports the same role set the runtime
 *    actually emits, including `tool` results and `assistant.tool_calls`.
 *
 * 3. **Every record carries provenance.** `source` says where the example came from
 *    (a real run, a synthetic seed, a human correction). Training on synthetic data
 *    without recording that fact is how projects quietly poison themselves.
 *
 * 4. **Outcome labels are explicit.** `outcome.verified` and `outcome.status` record
 *    whether the run actually succeeded and whether it was *verified*. This is what
 *    lets us build preference pairs (verified vs failed repair attempts) later
 *    without re-instrumenting anything.
 *
 * 5. **Versioned and additive.** `JDF_VERSION` gates compatibility. New fields may
 *    be added; existing ones are not repurposed, so old datasets stay readable.
 */

export const JDF_VERSION = '1.0.0'

/** How a training example came to exist. Provenance is not optional. */
export const SOURCE = {
  /** Captured from a real Javelin Core run against a real workspace. */
  RUNTIME_TRACE: 'runtime-trace',
  /** A human wrote or corrected this example. Highest trust. */
  HUMAN: 'human',
  /** Generated by a script from a template. Lowest trust; must stay labelled. */
  SYNTHETIC: 'synthetic',
  /** Derived from a repair cycle — valuable, since repair is the hard part. */
  REPAIR: 'repair',
}

/** Which Javelin cognitive phase an example teaches. */
export const SKILL = {
  TOOL_SELECTION: 'tool-selection',
  PLANNING: 'planning',
  EDIT_PRECISION: 'edit-precision',
  VERIFICATION: 'verification',
  REPAIR: 'repair',
  REFUSAL: 'refusal',
  HONESTY: 'honesty',
}

/**
 * @typedef {object} JdfMessage
 * @property {'system'|'user'|'assistant'|'tool'} role
 * @property {string|null} content
 * @property {{id: string, type: 'function', function: {name: string, arguments: string}}[]} [tool_calls]
 * @property {string} [tool_call_id]     present when role === 'tool'
 * @property {string} [name]             tool name when role === 'tool'
 */

/**
 * @typedef {object} JdfRecord
 * @property {string} id                 stable, content-derived
 * @property {string} version            JDF_VERSION at creation
 * @property {'sft'|'trajectory'|'preference'} kind
 * @property {string} source             one of SOURCE
 * @property {string} [skill]            one of SKILL (sft/preference)
 * @property {JdfMessage[]} [messages]   present for kind==='sft'
 * @property {object} [trajectory]       present for kind==='trajectory'
 * @property {object} [outcome]          labels: { status, verified, steps }
 * @property {object} [tools]            tool schemas in scope for this example
 * @property {object} [meta]             task text, model, timestamp, repo signature
 * @property {string[]} [tags]
 */

/** Fields every record must have, regardless of kind. */
const REQUIRED_COMMON = ['id', 'version', 'kind', 'source']

const VALID_KINDS = new Set(['sft', 'trajectory', 'preference'])
const VALID_ROLES = new Set(['system', 'user', 'assistant', 'tool'])

/**
 * Validate a single record.
 * Returns { ok, errors[] } — never throws, so a pipeline can report on a whole file.
 */
export function validateRecord(record) {
  const errors = []

  if (!record || typeof record !== 'object') {
    return { ok: false, errors: ['record is not an object'] }
  }

  for (const field of REQUIRED_COMMON) {
    if (record[field] == null || record[field] === '') {
      errors.push(`missing required field: ${field}`)
    }
  }

  if (record.kind && !VALID_KINDS.has(record.kind)) {
    errors.push(`invalid kind "${record.kind}" (expected ${[...VALID_KINDS].join(', ')})`)
  }
  if (record.source && !Object.values(SOURCE).includes(record.source)) {
    errors.push(`unknown source "${record.source}"`)
  }

  if (record.kind === 'sft' || record.kind === 'preference') {
    if (!Array.isArray(record.messages) || record.messages.length === 0) {
      errors.push('sft/preference record needs a non-empty messages[]')
    } else {
      errors.push(...validateMessages(record.messages))
    }
  }

  if (record.kind === 'trajectory' && (!record.trajectory || typeof record.trajectory !== 'object')) {
    errors.push('trajectory record needs a trajectory{} object')
  }

  if (record.kind === 'preference') {
    if (!record.chosen || !record.rejected) {
      errors.push('preference record needs both chosen{} and rejected{}')
    }
  }

  return { ok: errors.length === 0, errors }
}

function validateMessages(messages) {
  const errors = []

  for (let i = 0; i < messages.length; i++) {
    const m = messages[i]
    if (!m || typeof m !== 'object') {
      errors.push(`messages[${i}] is not an object`)
      continue
    }
    if (!VALID_ROLES.has(m.role)) {
      errors.push(`messages[${i}].role "${m.role}" is invalid`)
      continue
    }

    if (m.role === 'tool') {
      if (!m.tool_call_id) {
        errors.push(`messages[${i}] (tool) is missing tool_call_id`)
      }
    } else if (m.content == null && !m.tool_calls) {
      errors.push(`messages[${i}] (${m.role}) has neither content nor tool_calls`)
    }

    if (m.tool_calls) {
      if (!Array.isArray(m.tool_calls)) {
        errors.push(`messages[${i}].tool_calls must be an array`)
        continue
      }
      for (let j = 0; j < m.tool_calls.length; j++) {
        const tc = m.tool_calls[j]
        if (!tc?.id) {
          errors.push(`messages[${i}].tool_calls[${j}] is missing id`)
        }
        if (!tc?.function?.name) {
          errors.push(`messages[${i}].tool_calls[${j}] is missing function.name`)
        }
        if (typeof tc?.function?.arguments !== 'string') {
          // OpenAI-compatible format carries arguments as a JSON *string*.
          errors.push(
            `messages[${i}].tool_calls[${j}].function.arguments must be a JSON string, got ${typeof tc?.function?.arguments}`,
          )
        }
      }
    }
  }

  // Every tool result must reference a tool call that exists.
  const callIds = new Set()
  for (const m of messages) {
    for (const tc of m.tool_calls ?? []) {
      if (tc?.id) {
        callIds.add(tc.id)
      }
    }
  }
  for (let i = 0; i < messages.length; i++) {
    const m = messages[i]
    if (m.role === 'tool' && m.tool_call_id && !callIds.has(m.tool_call_id)) {
      errors.push(`messages[${i}] (tool) references unknown tool_call_id "${m.tool_call_id}"`)
    }
  }

  return errors
}

/** Validate a whole dataset (array of records) and summarise it. */
export function validateDataset(records) {
  if (!Array.isArray(records)) {
    return { ok: false, errors: ['dataset is not an array'], stats: null }
  }

  const errors = []
  const ids = new Set()
  const duplicates = []

  for (let i = 0; i < records.length; i++) {
    const res = validateRecord(records[i])
    if (!res.ok) {
      errors.push(...res.errors.map((e) => `record[${i}]: ${e}`))
    }
    const id = records[i]?.id
    if (id) {
      if (ids.has(id)) {
        duplicates.push(id)
      }
      ids.add(id)
    }
  }

  return {
    ok: errors.length === 0,
    errors,
    duplicates,
    stats: datasetStats(records),
  }
}

/** Aggregate counts, useful for eyeballing a dataset before training. */
export function datasetStats(records) {
  const byKind = {}
  const bySource = {}
  const bySkill = {}
  let verified = 0
  let totalMessages = 0
  let totalToolCalls = 0

  for (const r of records ?? []) {
    byKind[r.kind] = (byKind[r.kind] ?? 0) + 1
    bySource[r.source] = (bySource[r.source] ?? 0) + 1
    if (r.skill) {
      bySkill[r.skill] = (bySkill[r.skill] ?? 0) + 1
    }
    if (r.outcome?.verified) {
      verified++
    }
    for (const m of r.messages ?? []) {
      totalMessages++
      totalToolCalls += m.tool_calls?.length ?? 0
    }
  }

  return {
    total: records?.length ?? 0,
    byKind,
    bySource,
    bySkill,
    verified,
    totalMessages,
    totalToolCalls,
    avgMessages: records?.length ? +(totalMessages / records.length).toFixed(2) : 0,
  }
}

/**
 * JSONL serialisation. One record per line, which streams well and diffs cleanly.
 * A JSON array would force loading the entire dataset into memory.
 */
export function toJsonl(records) {
  return records.map((r) => JSON.stringify(r)).join('\n')
}

export function fromJsonl(text) {
  const records = []
  const errors = []
  const lines = text.split('\n')
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim()
    if (!line) {
      continue
    }
    try {
      records.push(JSON.parse(line))
    } catch (err) {
      errors.push(`line ${i + 1}: ${err.message}`)
    }
  }
  return { records, errors }
}

/**
 * Content-derived id. A stable id means re-exporting the same example produces the
 * same id, so deduplication works across runs and across machines.
 */
export function recordId(...parts) {
  const text = parts.join('|')
  let h = 5381
  for (let i = 0; i < text.length; i++) {
    h = ((h << 5) + h + text.charCodeAt(i)) | 0
  }
  return `jdf_${(h >>> 0).toString(36)}`
}

/**
 * Deduplicate by id, keeping the first occurrence.
 * Duplicates inflate a dataset's apparent size and over-weight whatever got
 * captured twice, so this runs before every export.
 */
export function dedupe(records) {
  const seen = new Set()
  const out = []
  for (const r of records) {
    if (!seen.has(r.id)) {
      seen.add(r.id)
      out.push(r)
    }
  }
  return out
}

/**
 * Deterministic train/validation split.
 * Deterministic so the same dataset always produces the same split — otherwise
 * evaluation numbers are not comparable between runs.
 */
export function split(records, { validationFraction = 0.1, seed = 1337 } = {}) {
  const shuffled = [...records]
  let state = seed
  const rand = () => {
    // xorshift32 — small, deterministic, good enough for shuffling.
    state ^= state << 13
    state ^= state >>> 17
    state ^= state << 5
    return ((state >>> 0) % 1e6) / 1e6
  }
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
      ;[shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]]
  }

  const cut = Math.max(1, Math.floor(shuffled.length * validationFraction))
  return {
    validation: shuffled.slice(0, cut),
    train: shuffled.slice(cut),
  }
}
